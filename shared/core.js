function renderHome() {
  const t = ymd(new Date()), recs = store.daily[t] || {}, st = streak();
  $('#daily-meta').innerHTML = todayLine(st);
  $('#daily-btns').replaceChildren(...Object.keys(TIERS).map((k, i) => {
    const b = document.createElement('button'), r = recs[k];
    b.className = `daily-btn tier-${k}${r ? ' done' : ''}`;
    b.style.setProperty('--i', i);
    b.innerHTML = `<b>${tierName(k)}</b><small>${r ? '✓ ' + fmt(r.t) : T(store.saves['D' + k + t] ? 'Resume' : 'Play')}</small>`;
    b.onclick = () => start(k, null, t);
    return b;
  }));
  $('#pack-btns').replaceChildren(...Object.keys(TIERS).map((k) => {
    const pp = store.packs[k], done = Object.keys(pp.stars).length;
    const b = document.createElement('button');
    b.className = `pack-btn tier-${k}`;
    b.innerHTML = `<span class="pack-name">${tierName(k)}</span>
      <span class="pack-bar"><i style="width:${(done / PACK_SIZE) * 100}%"></i></span>
      <span class="pack-count">${done}/${PACK_SIZE}</span>`;
    if (game.random) {
      const resume = !!store.saves[k + store.cur[k]];
      b.querySelector('.pack-count').insertAdjacentHTML('beforeend', `<small>${T(resume ? 'Resume' : 'New puzzle')}</small>`);
      b.onclick = () => playRandom(k);
      return b;
    }
    const next = firstUnsolved(pp);
    b.onclick = () => (next ? start(k, next) : openLevels(k));
    return b;
  }));
}

// ---------- play ----------
// start(pack, n) plays pack level n; start(pack, null, date) plays that day's daily of that difficulty.
function start(pack, n, date = null) {
  const key = date ? 'D' + pack + date : pack + n, save = store.saves[key] || {};
  G = { pack, n, date, key, elapsed: 0, hinted: new Set(), done: false, paused: false };
  track('start');
  $('#g-title').textContent = date ? T('Daily · {tier}', { tier: tierName(pack) }) : `${tierName(pack)} · ${game.random ? levelCode(n) : n}`;
  show('game');
  $('#game').classList.remove('done');
  $('#btn-result').hidden = true;
  toGame(levelHash(pack, n));
  if (game.start(G, save)) G.elapsed = save.elapsed || 0;
  setPaused(false);
  $('#timer').textContent = fmt(G.elapsed);
  clearInterval(timer);
  timer = setInterval(tick, 1000);
}

const playing = () => G && !G.done && !G.paused;

// Pause stops the clock and hides the board, so it can't be studied for free.
function setPaused(v) {
  if (!G || (v && G.done)) return;
  const changed = G.paused !== v;
  G.paused = v;
  $('#game').classList.toggle('paused', v);
  // the cover is the board's back: same size and corners, so the flip reads as one sheet turning over (core.css animates it)
  const c = $('#pause-cover'), b = $('#board');
  c.hidden = false;
  const r = b.getBoundingClientRect(); // ponytail: measured as shown; pausing again mid-resume measures the half-turned board, a hair short
  if (v && r.width) {
    c.style.setProperty('--sheet-w', r.width + 'px');
    c.style.setProperty('--sheet-h', r.height + 'px');
    c.style.setProperty('--sheet-r', getComputedStyle(b).borderRadius);
  }
  $('#btn-pause').innerHTML = v ? ICON_PLAY : ICON_PAUSE;
  $('#btn-pause').setAttribute('aria-label', T(v ? 'Resume' : 'Pause'));
  if (changed && v) { saveGame(); sfx.erase(); } else if (changed) sfx.tap();
}

function saveGame() {
  if (G.done) return;
  store.saves[G.key] = { ...game.save(G), elapsed: G.elapsed };
  persist();
}

function tick() {
  if (!G || G.done || G.paused || document.hidden || $('#game').hidden || document.querySelector('dialog[open]')) return;
  G.elapsed++;
  $('#timer').textContent = fmt(G.elapsed);
  if (G.elapsed % 5 === 0) saveGame();
}

// ★★☆ into el: each star stamps in on its own beat, with a rising note. fresh = false (a result seen again) sets them at once, quietly.
function starRow(el, n, fresh = true) {
  el.innerHTML = [0, 1, 2].map((i) => `<span class="${i < n ? 'on' : ''}" style="--i:${fresh ? i : -9}">★</span>`).join('');
  el.setAttribute('aria-label', T('{n} of 3 stars', { n }));
  if (fresh) for (let i = 0; i < n; i++) sfx.star(i);
}
// "Copied ✓" into a button label, its tick drawn in
const copied = (el) => { el.innerHTML = esc(T('Copied ✓')).replace('✓', TICK); };

function win() {
  const st = streak();
  G.done = true;
  clearInterval(timer);
  delete store.saves[G.key];
  const h = G.hinted.size, stars = h === 0 ? 3 : h <= 2 ? 2 : 1;
  if (G.date) ((store.daily[G.date] ??= {})[G.pack] ??= { t: G.elapsed, h });
  else {
    const pp = store.packs[G.pack];
    pp.stars[G.n] = Math.max(pp.stars[G.n] || 0, stars);
    pp.unlocked = Math.max(pp.unlocked, Math.min(G.n + 1, PACK_SIZE));
  }
  persist();
  bump(st);
  $('#board').classList.add('solved');
  $('#game').classList.add('done');
  sfx.win();
  confetti();
  track('finish');

  const g = G;
  setTimeout(() => {
    if (G !== g) return;
    starRow($('#win-stars'), stars);
    $('#win-title').textContent = T(['Brilliant!', 'Solved!', 'Nicely done!', 'Sharp!'][Math.floor(Math.random() * 4)]);
    $('#win-stats').innerHTML = `<b>${fmt(g.elapsed)}</b> · ${h ? hintsText(h) : T('no hints')}` + (g.date ? streakText(streak()) : '');
    const last = !g.date && !game.random && g.n === PACK_SIZE;
    if (last) $('#win-title').textContent = T('{tier} pack complete!', { tier: tierName(g.pack) });
    $('#win-next').hidden = last;
    $('#win-next b').textContent = g.date ? T('Share result') : game.random ? T('Another puzzle  →') : T('Level {n}  →', { n: g.n + 1 });
    $('#btn-result').hidden = false; // the dialog can be closed to look at the board; this brings it back
    $('#dlg-win').showModal();
  }, game.winDelay ?? 1100);
}

// Give up: the answer is shown, nothing is recorded (no stars, no daily), and the save is dropped.
function giveUp() {
  if (!playing() || !confirm(T("Give up and see the answer? This puzzle won't count as solved."))) return;
  G.done = true;
  clearInterval(timer);
  delete store.saves[G.key];
  persist();
  track('giveup');
  $('#game').classList.add('done');
  game.reveal(G);
  sfx.erase();
}

async function share() {
  track('share');
  const r = store.daily[G.date][G.pack];
  const text = `${T('{game} daily', { game: game.name })} · ${G.date} · ${tierName(G.pack)}\n⏱ ${fmt(r.t)}  ${r.h ? '💡'.repeat(r.h) : '⭐ ' + T('no hints')}` +
    (location.protocol.startsWith('http') ? '\n' + location.origin + location.pathname + '#' + levelHash(G.pack) : '');
  try {
    if (navigator.share) await navigator.share({ text });
    else { await navigator.clipboard.writeText(text); copied($('#win-next b')); }
  } catch {}
}

// Cut paper in the page's inks, overprinted (multiply on cream, screen on blue stock). A special day passes its own glyphs (its emoji);
// a streak milestone just reached (bumped) throws twice as much, higher.
function confetti(glyphs = game.glyphs) {
  if (matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const cv = $('#fx'), ctx = cv.getContext('2d'), dpr = devicePixelRatio || 1, W = innerWidth, H = innerHeight;
  cv.width = W * dpr; cv.height = H * dpr;
  const css = getComputedStyle(document.documentElement);
  const colors = ['--brand', '--brand', '--sun', '--teal', '--ink'].map((v) => css.getPropertyValue(v).trim());
  ctx.globalCompositeOperation = css.getPropertyValue('--blend').trim() || 'multiply';
  const big = MILESTONES.includes(bumped) ? 1.35 : 1;
  const parts = Array.from({ length: big > 1 ? 240 : 120 }, (_, i) => ({
    x: W / 2 + (Math.random() - 0.5) * 80, y: H * 0.42,
    vx: (Math.random() - 0.5) * 15 * big, vy: (-Math.random() * 14 - 5) * big,
    s: 7 + Math.random() * 8, a: Math.random() * 6, va: (Math.random() - 0.5) * 0.3, f: Math.random() * 6,
    c: colors[i % colors.length], g: i % 4 === 0 ? glyphs[i % glyphs.length] : null,
  }));
  ctx.globalAlpha = 0.9;
  ctx.font = '600 24px Fraunces, Georgia, serif'; // set once: per-particle font strings were the costliest part of a frame
  // ponytail: steps scale with real frame time, so dropped frames at win time (board restyle, dialog) don't play as slow motion
  let t0, last;
  function frame(now) {
    t0 ??= now;
    const k = Math.min((now - (last ?? now - 16.7)) / 16.7, 3);
    last = now;
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.clearRect(0, 0, cv.width, cv.height);
    for (const p of parts) {
      p.vy += 0.34 * k; p.vx *= 0.982 ** k; p.vy *= 0.992 ** k; p.x += p.vx * k; p.y += p.vy * k; p.a += p.va * k; p.f += 0.12 * k;
      // translate, rotate, then squash y as the paper flutters (its face turns toward and away from you); glyphs scale from the 24px font
      const z = dpr * (p.g ? p.s / 10 : 1), c = Math.cos(p.a) * z, sn = Math.sin(p.a) * z, fy = Math.cos(p.f);
      ctx.setTransform(c, sn, -sn * fy, c * fy, p.x * dpr, p.y * dpr);
      ctx.fillStyle = p.c;
      if (p.g) ctx.fillText(p.g, 0, 0);
      else ctx.fillRect(-p.s / 2, -p.s / 3, p.s, p.s / 1.5);
    }
    if (now - t0 < 3500) requestAnimationFrame(frame);
    else { ctx.setTransform(1, 0, 0, 1, 0, 0); ctx.clearRect(0, 0, cv.width, cv.height); }
  }
  requestAnimationFrame(frame);
}

// Idle nudge: 20s without input during play (active()), and #btn-hint hops once, as a quiet "psst". Any input starts a new idle spell.
// The interval skips paused, finished, hidden and dialog-covered time: active() and the checks below.
let lastInput = Date.now();
function nudge(active) {
  let nudged = false;
  for (const ev of ['pointerdown', 'keydown']) addEventListener(ev, () => { lastInput = Date.now(); nudged = false; }, true);
  setInterval(() => {
    const b = $('#btn-hint');
    if (nudged || Date.now() - lastInput < 20000 || !active() || document.hidden || document.querySelector('dialog[open]')) return;
    nudged = true;
    if (b && !b.disabled && b.offsetParent) flash(b, 'psst');
  }, 1000);
}

// 50 levels per page; opens on the page holding the first unsolved level.
const PAGE = 50;
const firstUnsolved = (pp) => Array.from({ length: pp.unlocked }, (_, i) => i + 1).find((n) => !pp.stars[n]);
function openLevels(pack = store.lastPack || 'E', page) {
  store.lastPack = pack;
  $('#pack-tabs').replaceChildren(...Object.keys(TIERS).map((k) => {
    const t = document.createElement('button');
    t.className = `tab tier-${k}`;
    t.textContent = tierName(k);
    t.setAttribute('aria-selected', String(k === pack));
    t.onclick = () => openLevels(k);
    return t;
  }));
  const pp = store.packs[pack], grid = $('#level-grid');
  const lastPage = Math.floor((pp.unlocked - 1) / PAGE);
  page ??= Math.floor(((firstUnsolved(pp) || pp.unlocked) - 1) / PAGE);
  const from = page * PAGE + 1, to = Math.min(from + PAGE - 1, PACK_SIZE);
  $('#pg-label').textContent = `${from}–${to}`;
  $('#pg-prev').disabled = page === 0;
  $('#pg-next').disabled = page >= lastPage;
  $('#pg-prev').onclick = () => openLevels(pack, page - 1);
  $('#pg-next').onclick = () => openLevels(pack, page + 1);
  grid.className = `level-grid tier-${pack}`;
  grid.replaceChildren();
  for (let n = from; n <= to; n++) {
    const b = document.createElement('button'), s = pp.stars[n] || 0;
    b.className = 'lvl' + (n === pp.unlocked && !s ? ' current' : '');
    b.disabled = n > pp.unlocked;
    b.innerHTML = `<span>${n}</span><small>${b.disabled ? '' : s ? '★'.repeat(s) + '☆'.repeat(3 - s) : ''}</small>`;
    b.setAttribute('aria-label', T(b.disabled ? 'Level {n}, locked' : s ? 'Level {n}, {s} stars' : 'Level {n}', { n, s }));
    b.onclick = () => { $('#dlg-levels').close(); start(pack, n); };
    grid.append(b);
  }
  if (!$('#dlg-levels').open) $('#dlg-levels').showModal();
  grid.querySelector('.current')?.scrollIntoView({ block: 'center' });
}

// ---------- print ----------
// Paper version of the puzzle on screen, unsolved. build() returns { top?: html (above the rules), rules: [html], body: html }.
// It fills #print right before printing (the #btn-print button or Ctrl+P); in print, core.css shows only #print, on one A4 page.
// From the menu nothing is filled, so the page prints as it looks.
function printable(build) {
  const out = document.createElement('section');
  out.id = 'print';
  document.body.append(out);
  addEventListener('beforeprint', () => {
    const s = !$('#game').hidden && build();
    out.innerHTML = s ? `<header class="p-head"><h1>${esc(game.name)}</h1><p>${esc([$('#g-title').textContent, $('#g-sub').textContent].filter(Boolean).join(' · '))}</p></header>${s.top || ''}` +
      `<ol class="rules">${s.rules.map((r) => `<li>${r}</li>`).join('')}</ol>${s.body}` : '';
    document.body.classList.toggle('printing', !!s);
  });
  $('#btn-print').onclick = () => print();
}

// ---------- boot ----------
function boot(g) {
  game = g;
  try { store = JSON.parse(localStorage.getItem(g.storeKey)) || {}; } catch { store = {}; }
  store = { packs: {}, daily: {}, saves: {}, muted: false, seenHelp: false, ...store };
  for (const k in TIERS) store.packs[k] ??= { unlocked: 1, stars: {} };
  if (g.random) {
    store.cur ??= {};
    // a level left mid-way under the old fixed progression becomes that difficulty's puzzle to resume
    for (const k in TIERS) store.cur[k] ??= +Object.keys(store.saves).find((s) => s[0] === k && /^\d+$/.test(s.slice(1)))?.slice(1) || undefined;
    for (const b of document.querySelectorAll('#new-row button')) b.onclick = () => playRandom(b.dataset.pack, true);
  } else $('#btn-levels').onclick = () => openLevels();
  $('#btn-help').onclick = () => { track('help', ''); $('#dlg-help').showModal(); };
  const home = () => { if (G && !G.done) saveGame(); clearInterval(timer); show('home'); };
  $('#btn-back').onclick = home;
  $('#btn-pause').onclick = () => setPaused(!G.paused);
  $('#btn-resume').onclick = () => setPaused(false);
  $('#btn-giveup').onclick = giveUp;
  $('#btn-result').onclick = () => $('#dlg-win').showModal();
  $('#win-home').onclick = () => { $('#dlg-win').close(); show('home'); };
  $('#win-next').onclick = () => {
    if (G.date) share(); else { $('#dlg-win').close(); game.random ? playRandom(G.pack, true) : start(G.pack, G.n + 1); }
  };
  $('#dlg-help').addEventListener('close', () => { store.seenHelp = true; persist(); });
  for (const b of document.querySelectorAll('.js-sound')) b.onclick = () => { store.muted = !store.muted; persist(); syncSound(true); sfx.tap(); };

  document.addEventListener('keydown', (e) => {
    if (!G || $('#game').hidden || document.querySelector('dialog[open]')) return;
    // Ctrl+Z / Cmd+Z clicks the game's undo button, if it has one and it's enabled.
    if ((e.ctrlKey || e.metaKey) && !e.shiftKey && !e.altKey && (e.key === 'z' || e.key === 'Z') && !e.target.closest('input, textarea')) {
      const u = $('#btn-undo');
      if (u && !u.disabled && !G.paused) { u.click(); e.preventDefault(); }
      return;
    }
    if (e.metaKey || e.ctrlKey || e.altKey) return;
    if (e.key === 'p' || e.key === 'P') { setPaused(!G.paused); return e.preventDefault(); }
    if (e.key === 'Escape') return $('#btn-back').click();
    if (G.paused) return;
    if (game.key(e)) e.preventDefault();
  });

  syncSound();
  nudge(() => playing() && !$('#game').hidden);
  router((h) => openLevel(h, start), home);
  if (!store.seenHelp) $('#dlg-help').showModal();
}
