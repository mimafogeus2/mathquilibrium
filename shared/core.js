// The shell every game shares: storage, sound, home menu, dailies & packs, timer, pause, levels, win, share.
// A game page loads common.js, core.js, then its own scripts, and calls boot(game) with:
//   name, storeKey, glyphs (confetti)
//   start(G, save) -> builds the board for G.key into #board; returns true if it restored `save`
//   save(G)        -> what to persist besides elapsed
//   key(e)         -> handle a keydown during play; return true if used
//   reveal(G)      -> show the answer on the board (after giving up)
//   random         -> optional: random levels per difficulty with share codes (playRandom), no unlocks or levels grid
// Games read and extend the shared G: { pack, n, date, key, elapsed, hinted: Set, done, paused }.
const $ = (s) => document.querySelector(s);
// the waves are their own paths, so core.css can ripple them out (on) or draw them back in (muted: they stay, invisible)
const SPEAKER = '<path d="M4 9v6h4l5 4V5L8 9H4z"/>', WAVES = '<path class="w" style="--i:0" d="M16.5 8.5a5 5 0 0 1 0 7"/><path class="w" style="--i:1" d="M19 6a8.5 8.5 0 0 1 0 12"/>';
const ICON_ON = `<svg viewBox="0 0 24 24">${SPEAKER}${WAVES}</svg>`;
const ICON_OFF = `<svg viewBox="0 0 24 24">${SPEAKER}<path class="x" d="M17 9l5 6M22 9l-5 6"/></svg>`;
const ICON_OFF_GO = `<svg viewBox="0 0 24 24">${SPEAKER}${WAVES}<path class="x" d="M17 9l5 6M22 9l-5 6"/></svg>`;
const TICK = '<svg class="tick" viewBox="0 0 24 24" aria-hidden="true"><path pathLength="1" d="M5 12.5l4.5 4.5L19 7.5"/></svg>';
const ICON_PAUSE = '<svg viewBox="0 0 24 24"><path d="M9 5v14M15 5v14"/></svg>';
const ICON_PLAY = '<svg viewBox="0 0 24 24"><path d="M7 5l12 7-12 7z"/></svg>';
// UI text. The source is English; a translated page (generated by build.js) defines I18N = { 'English': 'translation' } before any script.
// T('Level {n}', { n: 3 }) looks a string up and fills in its {placeholders}. LOCALE formats dates (undefined: the browser's own).
const LANG = document.documentElement.lang, LOCALE = LANG === 'en' ? undefined : LANG;
const T = (s, v = {}) => ((typeof I18N === 'object' && I18N[s]) || s).replace(/\{(\w+)\}/g, (_, k) => v[k]);
const tierName = (k) => T(TIERS[k]); // TIERS stay English: they're also URL hashes (#daily-easy)
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => `&#${c.charCodeAt(0)};`);

let game, store, G = null, timer = null;
const persist = () => { try { localStorage.setItem(game.storeKey, JSON.stringify(store)); } catch {} };

const ymd = (d) => d.toISOString().slice(0, 10); // UTC: the daily rolls over at midnight UTC, the same moment everywhere
const fmt = (s) => `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
// The Today header: "Thu 12 Nov · 4-day streak". HTML: a streak that just grew (bumped) has its number stamped in.
// The header shows it once, on the first menu after the win; then it's plain again.
let bumped = 0;
const MILESTONES = [7, 30, 100];
const streakText = (st) => (st ? ' · ' + T('{n}-day streak', { n: st === bumped ? `<b class="tick-n${MILESTONES.includes(st) ? ' lap' : ''}">${st}</b>` : st }) : '');
const todayLine = (st) => {
  const s = esc(new Date().toLocaleDateString(LOCALE, { weekday: 'short', day: 'numeric', month: 'short', timeZone: 'UTC' })) + streakText(st);
  bumped = 0;
  return s;
};
// Every finish calls this with the streak from before its result was recorded: a daily that grew the streak marks it as bumped.
const bump = (before) => { const st = streak(); bumped = st > before ? st : 0; };
const shortDate = (date) => new Date(date + 'T12:00').toLocaleDateString(LOCALE, { month: 'short', day: 'numeric' });
const hintsText = (h) => (h === 1 ? T('1 hint') : T('{n} hints', { n: h }));
function streak() {
  const d = new Date();
  const any = () => Object.keys(store.daily[ymd(d)] || {}).length > 0; // any difficulty counts
  if (!any()) d.setUTCDate(d.getUTCDate() - 1);
  let n = 0;
  for (; any(); d.setUTCDate(d.getUTCDate() - 1)) n++;
  return n;
}

// ---------- sound (synthesized, no assets) ----------
const sfx = (() => {
  let ctx;
  function tone(freq, { dur = 0.12, type = 'sine', vol = 0.15, at = 0, slide } = {}) {
    if (store.muted) return;
    try {
      ctx ??= new (window.AudioContext || window.webkitAudioContext)();
      if (ctx.state === 'suspended') ctx.resume();
      const t = ctx.currentTime + at, o = ctx.createOscillator(), g = ctx.createGain();
      o.type = type;
      o.frequency.setValueAtTime(freq, t);
      if (slide) o.frequency.exponentialRampToValueAtTime(slide, t + dur);
      g.gain.setValueAtTime(0.0001, t);
      g.gain.exponentialRampToValueAtTime(vol, t + 0.012);
      g.gain.exponentialRampToValueAtTime(0.0001, t + dur);
      o.connect(g).connect(ctx.destination);
      o.start(t);
      o.stop(t + dur + 0.05);
    } catch {}
  }
  const note = (semi) => 523.25 * 2 ** (semi / 12);
  const SCALE = [0, 2, 4, 7, 9, 12, 14, 16, 19, 21, 24];
  return {
    tap: () => tone(880, { dur: 0.04, type: 'triangle', vol: 0.05 }),
    place: () => { tone(440, { dur: 0.09, type: 'triangle', vol: 0.14, slide: 620 }); tone(1240, { dur: 0.05, vol: 0.03, at: 0.02 }); },
    erase: () => tone(360, { dur: 0.1, type: 'triangle', vol: 0.1, slide: 180 }),
    good: (n) => { const s = SCALE[Math.min(n, SCALE.length - 1)]; [0, 4, 7].forEach((d, i) => tone(note(s + d), { dur: 0.3, vol: 0.09, at: i * 0.05 })); },
    bad: () => { tone(196, { dur: 0.22, type: 'square', vol: 0.035, slide: 140 }); tone(185, { dur: 0.22, type: 'square', vol: 0.035, slide: 130 }); },
    star: (i) => tone(note([12, 16, 19][i]), { dur: 0.16, vol: 0.08, at: 0.5 + i * 0.16, type: 'triangle' }), // as each star lands (.stars in core.css)
    hint: () => [12, 19, 24].forEach((s, i) => tone(note(s), { dur: 0.18, vol: 0.06, at: i * 0.07, type: 'triangle' })),
    win: () => [0, 4, 7, 12, 7, 12, 16, 19, 24].forEach((s, i) =>
      tone(note(s), { dur: i === 8 ? 0.9 : 0.22, vol: 0.1, at: i * 0.085, type: i % 2 ? 'triangle' : 'sine' })),
  };
})();

function syncSound(go) {
  for (const b of document.querySelectorAll('.js-sound')) {
    b.innerHTML = store.muted ? (go ? ICON_OFF_GO : ICON_OFF) : ICON_ON;
    if (go) b.firstChild.classList.add('go', store.muted ? 'off' : 'on');
    b.setAttribute('aria-pressed', String(!store.muted));
  }
}

function flash(el, cls) {
  el.classList.remove('pop', 'shake', 'psst');
  void el.getBoundingClientRect();
  el.classList.add(cls);
  el.addEventListener('animationend', () => el.classList.remove(cls), { once: true });
}

// ---------- URLs ----------
// Each puzzle has its own hash (#daily-easy, #easy-12, ...); the menu has none. Menu -> puzzle pushes a history entry,
// puzzle -> puzzle replaces it, so Back returns to the menu and Forward to the last puzzle played from it.
// Anonymous GoatCounter event, e.g. "coronet/finish/daily-hard": no cookies, nothing personal, same data as a page view.
// A no-op when count.js is blocked or not loaded (localhost, file://). The mode defaults to the boot() game's puzzle in play.
const mode = (date, tier) => (date ? 'daily' : 'level') + (tier ? '-' + tier.toLowerCase() : '');
function track(what, m = G && mode(G.date, TIERS[G.pack])) {
  const g = location.pathname.replace(/index\.html$/, '').split('/').filter(Boolean).pop();
  window.goatcounter?.count?.({ path: `${g}/${what}` + (m ? '/' + m : ''), event: true });
}
function toGame(h) {
  if (location.hash) history.replaceState(history.state, '', '#' + h);
  else history.pushState('game', '', '#' + h);
}
// Back to the menu: onto the menu's own entry when this one was pushed from it (so Forward still works), else turn this entry into the menu.
function toMenu(back = true) {
  if (!location.hash) return;
  if (back && history.state === 'game') history.back();
  else history.replaceState(null, '', location.pathname + location.search);
}
// Show what the hash names on load and on Back/Forward: open(hash) returns true if it opened something, else home() runs.
function router(open, home) {
  const go = () => {
    for (const d of document.querySelectorAll('dialog[open]')) d.close();
    if (!open(decodeURIComponent(location.hash.slice(1)))) home();
  };
  addEventListener('hashchange', go);
  go();
}
// Pack games: #daily-easy is today's Easy daily, #easy-12 is Easy level 12 (if unlocked).
// Random games (game.random) use an opaque 3-char code instead (#easy-k3f), and any level opens, unlocked or not.
// n * 9973 mod 36^3 is a bijection (9973 is coprime with 36^3), so codes don't follow level order (as in Orderly).
const levelCode = (n) => ((n * 9973) % 46656).toString(36).padStart(3, '0');
const levelHash = (pack, n) => (n ? '' : 'daily-') + TIERS[pack].toLowerCase() + (n ? '-' + (game.random ? levelCode(n) : n) : '');
function openLevel(h, start) {
  const [a, b] = h.split('-'), tier = (s) => Object.keys(TIERS).find((k) => TIERS[k].toLowerCase() === s), p = tier(a);
  const n = game.random ? Array.from({ length: PACK_SIZE }, (_, i) => i + 1).find((i) => levelCode(i) === b) : +b;
  if (a === 'daily' && tier(b)) start(tier(b), null, ymd(new Date()));
  else if (p && game.random && n) { store.cur[p] = n; persist(); start(p, n); }
  else if (p && Number.isInteger(n) && n >= 1 && n <= store.packs[p].unlocked) start(p, n);
  else return false;
  return true;
}
// Random games: store.cur[pack] is that difficulty's puzzle in play, resumed until solved or given up (or a new one is dealt).
// A new one is a random unsolved level of the pack (any level once all are solved).
function playRandom(pack, fresh) {
  const cur = store.cur[pack];
  if (fresh || !store.saves[pack + cur]) {
    delete store.saves[pack + cur];
    const all = Array.from({ length: PACK_SIZE }, (_, i) => i + 1), open = all.filter((n) => !store.packs[pack].stars[n]);
    store.cur[pack] = pick(Math.random, open.length ? open : all);
    persist();
  }
  start(pack, store.cur[pack]);
}

