// node build.js — writes the translated pages (he/index.html, he/<game>/index.html) from the English ones and i18n/<lang>.js.
// The English pages are the source and need no build. The output is committed (GitHub Pages serves the repo as is):
// run this after changing a page or a translation. `node build.js --check` only verifies the committed output is up to date.
// It fails on a translation that no longer matches the English, a T('...') string without a translation, or English left on a page.
'use strict';
const fs = require('fs'), path = require('path');
const LANGS = ['he'];
const PAGES = ['index.html', ...['mathquilibrium', 'biggr', 'wordswipe', 'orderly', 'coronet', 'quadflip'].map((g) => g + '/index.html')];
const SITE = 'https://mimafogeus2.github.io/mathquilibrium/';
const ROOT = __dirname, read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const check = process.argv.includes('--check'), errors = [];

// The literal strings a script passes to T() (a template with ${} is looked up at runtime and can't be checked here)
const keysIn = (src) => [...src.matchAll(/\bT\((['"`])((?:\\.|(?!\1).)*)\1/g)].filter((m) => !m[2].includes('${')).map((m) => (0, eval)(m[1] + m[2] + m[1]));

for (const lang of LANGS) {
  const D = require(`./i18n/${lang}.js`), common = D.html['*'], seen = new Set();
  for (const [file, strings] of Object.entries(D.js)) {
    const src = read(file);
    for (const k of keysIn(src)) if (!(k in strings) && !(k in D.js['shared/core.js'])) errors.push(`${lang}: ${file} has T(${JSON.stringify(k)}) with no translation`);
  }

  for (const page of PAGES) {
    const out = path.join(lang, page), dir = path.dirname(page);
    let html = read(page);
    const swap = (en, tr, where) => {
      if (!html.includes(en)) return where && errors.push(`${lang} ${page}: not found: ${en.slice(0, 120)}`);
      html = html.split(en).join(tr);
      return true;
    };
    // longest first, so a block (a help list) is swapped before any phrase inside it (its <b>Check</b>)
    const byLength = (pairs) => [...pairs].sort((a, b) => b[0].length - a[0].length);
    for (const [en, tr] of byLength(D.html[page] || [])) swap(en, tr, true);
    for (const [en, tr] of byLength(common)) if (swap(en, tr, false)) seen.add(en);

    swap('<html lang="en">', `<html lang="${lang}" dir="${D.dir}">`, true);
    swap('&family=Inter:wght@400..700', '&family=Inter:wght@400..700' + D.fonts, true);
    swap(`<meta property="og:url" content="${SITE}${dir === '.' ? '' : dir + '/'}">`, `<meta property="og:url" content="${SITE}${lang}/${dir === '.' ? '' : dir + '/'}">`, true);

    // Share image: the translation's own, rendered from shared/og.html?lang=<lang>
    if (fs.existsSync(path.join(ROOT, lang, dir, 'og.png'))) swap(`content="${SITE}${dir === '.' ? '' : dir + '/'}og.png"`, `content="${SITE}${lang}/${dir === '.' ? '' : dir + '/'}og.png"`, true);

    // Local files: a page link stays relative (it's the translated page); a file the translation has its own copy of
    // (he/orderly/levels.js) stays too; anything else points back at the English file.
    html = html.replace(/(\b(?:src|href)=")([^"#:]*)"/g, (m, a, url) => {
      if (url === '' || url.endsWith('/') || fs.existsSync(path.join(ROOT, lang, dir, url))) return m;
      return a + path.relative(path.join(lang, dir), path.join(dir, url)).split(path.sep).join('/') + '"';
    });

    // The strings of the scripts this page loads, inlined first thing so every script (theme.js in <head> too) can use them
    const scripts = [...read(page).matchAll(/<script src="([^"]+)"/g)].map((m) => path.join(dir, m[1]).split(path.sep).join('/'));
    const strings = Object.assign({}, ...scripts.map((s) => D.js[s] || {}));
    swap('<meta charset="utf-8">', `<meta charset="utf-8">\n<script>var I18N = ${JSON.stringify(strings)};</script>`, true);
    html = html.replace('<!doctype html>', `<!doctype html>\n<!-- Generated by build.js from ${page} and i18n/${lang}.js: edit those, then run node build.js -->`);

    // English left on the page (text and labels; not scripts, styles, key caps or the word-free bits of SVG art)
    const text = html.replace(/<(script|style|kbd)\b[^]*?<\/\1>/g, ' ').replace(/<!--[^]*?-->/g, ' ')
      .replace(/<meta\b[^>]*>/g, (t) => (/description|og:title|og:site_name/.test(t) ? ' ' + t.match(/content="([^"]*)"/)[1] + ' ' : ' '))
      .replace(/<[^>]*?\b(?:aria-label|title|alt)="([^"]*)"[^>]*>/g, ' $1 ').replace(/<[^>]+>/g, ' ').replace(/&\w+;/g, ' ');
    const left = [...new Set(text.match(/[A-Za-z][A-Za-z']+/g) || [])].filter((w) => !(D.keep || []).includes(w));
    if (left.length) errors.push(`${lang} ${page}: untranslated: ${left.join(' ')}`);

    if (check) { if (!fs.existsSync(path.join(ROOT, out)) || read(out) !== html) errors.push(`${out} is out of date: run node build.js`); }
    else { fs.mkdirSync(path.join(ROOT, lang, dir), { recursive: true }); fs.writeFileSync(path.join(ROOT, out), html); }
  }
  for (const [en] of common) if (!seen.has(en)) errors.push(`${lang}: '*' text found on no page: ${en}`);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
console.log(check ? 'translated pages up to date' : `wrote ${LANGS.length * PAGES.length} pages`);
