// node smallfry/build-levels.js [packs] [days] — writes smallfry/levels.js: `packs` levels each of Easy, Medium and Hard (default
// 1000), and `days` dailies of each difficulty and of Impossible (default 365) from DAY0 on. Levels come from gen.js seeded by
// their key ('E12', 'DH2026-11-20'), so a rerun writes the same lines: to add more, run it again with bigger numbers.
// Hard and Impossible take a while (a few seconds a level), so it spreads the work over every core.
const { Worker, isMainThread, parentPort } = require('worker_threads');
const os = require('os'), fs = require('fs'), path = require('path');
Object.assign(globalThis, require('../shared/common.js'));
const { generate, line } = require('./gen.js');
const DAY0 = '2026-11-18';

if (!isMainThread) {
  parentPort.on('message', ({ key, tier }) => parentPort.postMessage({ key, line: line(generate(hash(key), tier)) }));
} else {
  const packs = +(process.argv[2] ?? 1000), days = +(process.argv[3] ?? 365), jobs = [], out = {};
  const date = (i) => new Date(Date.parse(DAY0) + i * 864e5).toISOString().slice(0, 10);
  // the slow ones first, so the cores stay busy to the end
  for (const tier of ['I', 'H', 'M', 'E']) {
    if (tier !== 'I') for (let n = 1; n <= packs; n++) jobs.push({ key: tier + n, tier });
    for (let i = 0; i < days; i++) jobs.push({ key: 'D' + tier + date(i), tier });
  }
  let next = 0, done = 0;
  const t0 = Date.now(), N = Math.max(1, os.cpus().length - 1);
  const finish = () => {
    const LEVELS = {}, DAILY = { from: DAY0 };
    for (const tier of ['E', 'M', 'H']) LEVELS[tier] = Array.from({ length: packs }, (_, n) => out[tier + (n + 1)]);
    for (const tier of ['E', 'M', 'H', 'I']) DAILY[tier] = Array.from({ length: days }, (_, i) => out['D' + tier + date(i)]);
    const js = (o) => '{\n' + Object.entries(o).map(([k, v]) => `  ${k}: ${Array.isArray(v) ? '[\n' + v.map((l) => '    ' + JSON.stringify(l)).join(',\n') + ',\n  ]' : JSON.stringify(v)}`).join(',\n') + ',\n}';
    fs.writeFileSync(path.join(__dirname, 'levels.js'), `// Generated by build-levels.js (${packs} levels a pack, ${days} dailies from ${DAY0}): don't edit by hand. Format: gen.js, line().\n` +
      `const LEVELS = ${js(LEVELS)};\nconst DAILY = ${js(DAILY)};\nif (typeof module === 'object') module.exports = { LEVELS, DAILY };\n`);
    console.log(`wrote ${jobs.length} levels in ${Math.round((Date.now() - t0) / 1000)}s`);
    process.exit();
  };
  for (let w = 0; w < N; w++) {
    const worker = new Worker(__filename);
    const feed = () => (next < jobs.length ? worker.postMessage(jobs[next++]) : worker.terminate());
    worker.on('message', (m) => {
      out[m.key] = m.line;
      if (++done % 100 === 0) console.log(`${done}/${jobs.length} ${Math.round((Date.now() - t0) / 1000)}s`);
      if (done === jobs.length) finish();
      feed();
    });
    feed();
  }
}
