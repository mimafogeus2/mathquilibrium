// node smallfry/build-levels.js [packs] [days] [impossible days] [workers] — writes smallfry/levels.js: `packs` levels each of
// Easy, Medium and Hard (default 1000), `days` dailies of each from DAY0 on (default 365), and `impossible days` Impossible
// dailies (default 60: by far the slowest to make). Levels come from gen.js seeded by their key ('E12', 'DH2026-11-20'), so a
// rerun makes the same lines: to add more, run it again with bigger numbers.
// Every level is saved to smallfry/levels-cache.txt the moment it's made, so a stopped run loses nothing and a rerun only makes
// what's missing. The fast tiers go first, Impossible last. workers (default 6) is kept below the core count: the uniqueness
// search holds a lot in memory, and a machine that starts swapping crawls.
// Prints `done/total seconds` every 25 levels, `wrote N levels` at the end.
const { Worker, isMainThread, parentPort } = require('worker_threads');
const fs = require('fs'), path = require('path');
Object.assign(globalThis, require('../shared/common.js'));
const { generate, line } = require('./gen.js');
const DAY0 = '2026-11-18', CACHE = path.join(__dirname, 'levels-cache.txt');

if (!isMainThread) {
  parentPort.on('message', ({ key, tier }) => parentPort.postMessage({ key, line: line(generate(hash(key), tier)) }));
} else {
  const [packs = 1000, days = 365, impDays = 60, workers = 6] = process.argv.slice(2).map(Number);
  const date = (i) => new Date(Date.parse(DAY0) + i * 864e5).toISOString().slice(0, 10);
  const out = {};
  if (fs.existsSync(CACHE)) for (const l of fs.readFileSync(CACHE, 'utf8').split('\n')) { const i = l.indexOf('\t'); if (i > 0) out[l.slice(0, i)] = l.slice(i + 1); }
  const all = [];
  for (const tier of ['E', 'M', 'H']) for (let n = 1; n <= packs; n++) all.push({ key: tier + n, tier });
  for (const tier of ['E', 'M', 'H']) for (let i = 0; i < days; i++) all.push({ key: 'D' + tier + date(i), tier });
  for (let i = 0; i < impDays; i++) all.push({ key: 'DI' + date(i), tier: 'I' });
  const jobs = all.filter((j) => !(j.key in out)), total = all.length, t0 = Date.now();
  let next = 0, done = total - jobs.length;
  console.log(`${done}/${total} cached, ${jobs.length} to make on ${workers} workers`);
  const finish = () => {
    const LEVELS = {}, DAILY = { from: DAY0 };
    for (const tier of ['E', 'M', 'H']) LEVELS[tier] = Array.from({ length: packs }, (_, n) => out[tier + (n + 1)]);
    for (const tier of ['E', 'M', 'H']) DAILY[tier] = Array.from({ length: days }, (_, i) => out['D' + tier + date(i)]);
    DAILY.I = Array.from({ length: impDays }, (_, i) => out['DI' + date(i)]);
    const js = (o) => '{\n' + Object.entries(o).map(([k, v]) => `  ${k}: ${Array.isArray(v) ? '[\n' + v.map((l) => '    ' + JSON.stringify(l)).join(',\n') + ',\n  ]' : JSON.stringify(v)}`).join(',\n') + ',\n}';
    fs.writeFileSync(path.join(__dirname, 'levels.js'), `// Generated by build-levels.js (${packs} levels a pack, ${days} dailies and ${impDays} Impossible ones from ${DAY0}): don't edit by hand. Format: gen.js, line().\n` +
      `const LEVELS = ${js(LEVELS)};\nconst DAILY = ${js(DAILY)};\nif (typeof module === 'object') module.exports = { LEVELS, DAILY };\n`);
    console.log(`wrote ${total} levels in ${Math.round((Date.now() - t0) / 1000)}s`);
    process.exit();
  };
  if (!jobs.length) finish();
  for (let w = 0; w < Math.min(workers, jobs.length); w++) {
    const worker = new Worker(__filename);
    const feed = () => (next < jobs.length ? worker.postMessage(jobs[next++]) : worker.terminate());
    worker.on('message', (m) => {
      out[m.key] = m.line;
      fs.appendFileSync(CACHE, m.key + '\t' + m.line + '\n');
      if (++done % 25 === 0) console.log(`${done}/${total} ${Math.round((Date.now() - t0) / 1000)}s`);
      if (done === total) finish();
      feed();
    });
    feed();
  }
}
