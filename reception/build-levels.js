// node reception/build-levels.js [days] [workers] — writes reception/levels.js: Impossible Mode's dailies from DAY0 on (default 365),
// the one tier too slow to make in the page (Easy, Medium and Hard are; game.js LIVE). Levels come from gen.js seeded by their
// key ('DI2026-11-23'), so a rerun makes the same lines: to add more, run it again with a bigger number.
// Every level is saved to reception/levels-cache.txt the moment it's made, so a stopped run loses nothing and a rerun only makes
// what's missing. workers (default 6) is kept below the core count: the uniqueness search holds a lot in memory.
// Prints `done/total seconds` every 25 levels, `wrote N levels` at the end.
const { Worker, isMainThread, parentPort } = require('worker_threads');
const fs = require('fs'), path = require('path');
Object.assign(globalThis, require('../shared/common.js'));
const { generate, line } = require('./gen.js');
const DAY0 = '2026-11-23', CACHE = path.join(__dirname, 'levels-cache.txt');

if (!isMainThread) {
  parentPort.on('message', ({ key, tier }) => parentPort.postMessage({ key, line: line(generate(hash(key), tier)) }));
} else {
  const [days = 365, workers = 6] = process.argv.slice(2).map(Number);
  const date = (i) => new Date(Date.parse(DAY0) + i * 864e5).toISOString().slice(0, 10);
  const out = {};
  if (fs.existsSync(CACHE)) for (const l of fs.readFileSync(CACHE, 'utf8').split('\n')) { const i = l.indexOf('\t'); if (i > 0) out[l.slice(0, i)] = l.slice(i + 1); }
  const all = [];
  for (let i = 0; i < days; i++) all.push({ key: 'DI' + date(i), tier: 'I' });
  const jobs = all.filter((j) => !(j.key in out)), total = all.length, t0 = Date.now();
  let next = 0, done = total - jobs.length;
  console.log(`${done}/${total} cached, ${jobs.length} to make on ${workers} workers`);
  const finish = () => {
    const DAILY = { from: DAY0, I: Array.from({ length: days }, (_, i) => out['DI' + date(i)]) };
    const js = (o) => '{\n' + Object.entries(o).map(([k, v]) => `  ${k}: ${Array.isArray(v) ? '[\n' + v.map((l) => '    ' + JSON.stringify(l)).join(',\n') + ',\n  ]' : JSON.stringify(v)}`).join(',\n') + ',\n}';
    fs.writeFileSync(path.join(__dirname, 'levels.js'), `// Generated by build-levels.js (${days} Impossible dailies from ${DAY0}): don't edit by hand. Format: gen.js, line().\n` +
      `const DAILY = ${js(DAILY)};\nif (typeof module === 'object') module.exports = { DAILY };\n`);
    console.log(`wrote ${total} levels in ${Math.round((Date.now() - t0) / 1000)}s`);
    process.exit();
  };
  if (!jobs.length) finish();
  for (let w = 0; w < Math.min(workers, jobs.length); w++) {
    const worker = new Worker(__filename);
    const feed = () => (next < jobs.length ? worker.postMessage(jobs[next++]) : worker.terminate());
    worker.on('message', (m) => {
      out[m.key] = m.line;
      fs.appendFileSync(CACHE, m.key + '\t' + m.line + '\n');
      if (++done % 25 === 0) console.log(`${done}/${total} ${Math.round((Date.now() - t0) / 1000)}s`);
      if (done === total) finish();
      feed();
    });
    feed();
  }
}
