'use strict';
// node lexiconga/build-words.js <scowl final/ dir> <FrequencyWords en_50k.txt> <FrequencyWords he_full.txt> [--gen]
// Writes the word lists Lexiconga loads:
//   lexiconga/words.js, he/lexiconga/words.js         WORDS: every word a player may type (the check). May grow between builds.
//   lexiconga/gen-words.js, he/lexiconga/gen-words.js GEN_WORDS: common words, most frequent first, that levels are dealt from and
//     hints suggest. Levels are seeded from it, so it's FROZEN: rewritten only with --gen (every level and daily changes).
// Sources (download them anywhere; nothing here is committed but the output):
//   SCOWL 2020.12.07 (wordlist.aspell.net, MIT-like licence: see lexiconga/CREDITS.md), sizes up to 60, US + UK spellings
//   hermitdave/FrequencyWords 2018 (OpenSubtitles, CC BY-SA 4.0): en_50k.txt ranks the English; he_full.txt is the whole Hebrew list
// Hebrew words are stored with final letters as regular ones (ך→כ…), the way the game compares them.
const fs = require('fs'), path = require('path');
const [scowlDir, enFreq, heFreq] = process.argv.slice(2).filter((a) => !a.startsWith('--')), GEN = process.argv.includes('--gen');
if (!heFreq) { console.error('usage: node lexiconga/build-words.js <scowl final dir> <en_50k.txt> <he_full.txt> [--gen]'); process.exit(1); }
const ROOT = path.join(__dirname, '..');
const write = (file, name, words, note) => {
  fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, file), `// ${note}\n// Generated by lexiconga/build-words.js: don't edit by hand.\nconst ${name} = '${words.join(' ')}';\n`);
  console.log(`${file}: ${words.length} words`);
};
const freq = (f, min) => fs.readFileSync(f, 'utf8').split('\n').map((l) => l.split(' ')).filter(([w, c]) => w && +c >= min).map(([w, c]) => [w, +c]);

// Never dealt into a level or suggested by a hint (they can still be typed)
const RUDE_EN = 'gonna wanna gotta kinda sorta outta lemme gimme dunno fuck fucking fucked fucker shit shitty damn damned bitch bitches ass asses asshole bastard crap dick dicks cock cocks pussy whore whores slut sluts piss pissed cunt fag faggot nigger nigga retard retarded rape raped rapist tits boobs penis vagina sexy sex horny porn nazi nazis jerk hell bloody suck sucks sucker screw screwed kill killed killing killer murder murdered suicide dead die died dying drugs cocaine heroin'.split(' ');
const RUDE_HE = 'חרא זין מזוינ מזדיינ כלבה זונה זונות תחת לעזאזל פאק כוס זיונ לזיינ מניאק מטומטמ דפוק רצח רוצח למות מת מתה מתימ גופה סמימ'.split(' ');

// ---------- English ----------
{
  const files = fs.readdirSync(scowlDir).filter((f) => /^(english|american|british_variant_1)-words\.\d+$/.test(f) && +f.split('.')[1] <= 60);
  const all = new Set(), core = new Set(); // core: sizes up to 50, the plainer words, for dealing
  for (const f of files) for (const w of fs.readFileSync(path.join(scowlDir, f), 'latin1').split('\n')) {
    if (!/^[a-z]{2,}$/.test(w)) continue;
    all.add(w);
    if (+f.split('.')[1] <= 50) core.add(w);
  }
  write('lexiconga/words.js', 'WORDS', [...all].sort(), 'Every English word a player may type: SCOWL size 60 (US and UK spellings).');
  if (GEN) write('lexiconga/gen-words.js', 'GEN_WORDS', freq(enFreq, 1).map(([w]) => w).filter((w) => w.length >= 3 && core.has(w) && !RUDE_EN.includes(w)).slice(0, 20000),
    'English words levels are dealt from, most frequent first (FrequencyWords en_50k, CC BY-SA 4.0, within SCOWL 50). Frozen: levels are seeded from it.');
}

// ---------- Hebrew ----------
{
  const FIN = { 'ך': 'כ', 'ם': 'מ', 'ן': 'נ', 'ף': 'פ', 'ץ': 'צ' }, norm = (w) => w.replace(/[ךםןףץ]/g, (c) => FIN[c]);
  const cnt = new Map();
  for (const [w, c] of freq(heFreq, 10)) if (/^[א-ת]+$/.test(w)) { const k = norm(w); cnt.set(k, (cnt.get(k) || 0) + c); }
  // Attached prefixes (ו ה ב כ ש: and, the, in, as, that): והבית, הבית and בבית are בית, not words of their own. A word is taken for a
  // prefixed form when it's one of those letters on a word at least as common as itself. ל and מ are left alone: they start infinitives
  // (לדבר) and a whole family of nouns (מדבר, מקרה). ponytail: a frequency heuristic; ALLOW puts back the real words it catches.
  const ALLOW = 'כנראה כלומר ביחד שאלה שאלות כאלה כאלו שואל הורג הלכו שקרנ שלמה כפול בקשה כניסה שלילי כלפי שמימ הבינ הראה בקשר בעלה ברכה ברכות ברור בדיוק בסדר שלומ הרבה שלוש בוקר בחור כמעט כמובנ'.split(' ').map(norm);
  const prefixed = (w) => w.length >= 4 && 'והבכש'.includes(w[0]) && cnt.get(w.slice(1)) >= cnt.get(w) && !ALLOW.includes(w);
  const words = [...cnt.keys()].filter((w) => !prefixed(w));
  write('he/lexiconga/words.js', 'WORDS', words.sort(), 'Every Hebrew word a player may type (final letters as regular ones): FrequencyWords he, CC BY-SA 4.0, without attached prefixes.');
  // For dealing: nouns and adjectives, told by taking the article often (הבית is at least a tenth as common as בית): names and verbs rarely do
  if (GEN) {
    const set = new Set(words);
    write('he/lexiconga/gen-words.js', 'GEN_WORDS', words.filter((w) => w.length >= 3 && (cnt.get('ה' + w) || 0) >= cnt.get(w) / 10 && !RUDE_HE.includes(w) && set.has(w))
      .sort((a, b) => cnt.get(b) - cnt.get(a)).slice(0, 12000),
    'Hebrew words levels are dealt from, most frequent first (FrequencyWords he, CC BY-SA 4.0; final letters as regular ones). Frozen: levels are seeded from it.');
  }
}
